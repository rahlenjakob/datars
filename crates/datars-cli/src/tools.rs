/// Every std recipe (id → description), or one (`std/bar`, `bar` or `@datars/std/bar`).
pub fn describe(all: &BTreeMap<String, Value>, which: Option<&str>, json_out: bool) -> Result<String, String> {
    let Some(w) = which else {
        if json_out {
            return Ok(serde_json::to_string_pretty(all).unwrap_or_default());
        }
        let mut s = String::new();
        for (id, d) in all {
            let doc = d["doc"].as_str().unwrap_or("");
            let first = doc.split(". ").next().unwrap_or(doc).trim_end_matches('.');
            s += &format!("{:<28} {first}\n", id.trim_start_matches("@datars/"));
        }
        return Ok(s);
    };
    let id = format!("@datars/std/{}", w.trim_start_matches("@datars/").trim_start_matches("std/"));
    let d = all.get(&id).ok_or_else(|| format!("no recipe `{id}` (datars describe lists them)"))?;
    if json_out {
        return Ok(serde_json::to_string_pretty(d).unwrap_or_default());
    }
    let mut s = format!("{id}\n{}\n\nparams:\n", d["doc"].as_str().unwrap_or(""));
    for (name, p) in d["params"].as_object().into_iter().flatten() {
        let ty = p["type"].as_str().unwrap_or("?");
        let def = p.get("default").map(|v| format!(" = {v}")).unwrap_or_default();
        let doc = p["doc"].as_str().map(|d| format!("  — {d}")).unwrap_or_default();
        s += &format!("  {name}: {ty}{def}{doc}\n");
    }
    if let Some(t) = d["tokens"].as_array().filter(|t| !t.is_empty()) {
        s += &format!("\ntheme tokens: {}\n", t.iter().filter_map(|v| v.as_str()).collect::<Vec<_>>().join(", "));
    }
    Ok(s)
}

// ---- datars docs ---------------------------------------------------------------------------

fn first_sentence(doc: &str) -> &str {
    let end = doc.find(". ").map(|i| i + 1).unwrap_or(doc.len());
    doc[..end].trim_end_matches('.').trim()
}

/// The standard library reference, generated from the recipes' own descriptions (params,
/// defaults, docs, theme tokens) — it can't drift from the code.
pub fn reference_md(all: &BTreeMap<String, Value>) -> String {
    let mut s = String::from("# Standard library reference\n\n*Generated by `datars docs` from the recipes themselves — do not edit.* Every recipe is TypeScript in `packages/std/src`, written against the public SDK; `datars eject std/<name>` copies one into your project.\n\n");
    for id in all.keys() {
        let short = id.trim_start_matches("@datars/std/");
        s += &format!("- [`{short}`](#{short})\n");
    }
    for (id, d) in all {
        let short = id.trim_start_matches("@datars/std/");
        s += &format!("\n## {short}\n\n`{id}` — {}\n\n", d["doc"].as_str().unwrap_or(""));
        let params = d["params"].as_object();
        if params.is_some_and(|p| !p.is_empty()) {
            s += "| param | type | default | |\n|---|---|---|---|\n";
            for (name, p) in params.into_iter().flatten() {
                let def = p.get("default").map(|v| format!("`{v}`")).unwrap_or_default();
                let doc = p["doc"].as_str().unwrap_or("").replace('|', "\\|");
                s += &format!("| `{name}` | {} | {def} | {doc} |\n", p["type"].as_str().unwrap_or(""));
            }
        }
        if let Some(t) = d["tokens"].as_array().filter(|t| !t.is_empty()) {
            s += &format!("\nTheme tokens: {}\n", t.iter().filter_map(|v| v.as_str()).map(|t| format!("`{t}`")).collect::<Vec<_>>().join(", "));
        }
    }
    s
}

