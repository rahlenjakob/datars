/// A bundle's variants and chunks (raw and gzipped), and which variant each kind of runtime picks.
pub fn bundle_inspect(bytes: &[u8]) -> Result<Value, String> {
    let b = datars_bundle::from_single_file(bytes).map_err(|e| e.to_string())?;
    let m = &b.manifest;
    let gz = |c: &[u8]| {
        use std::io::Write;
        let mut e = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::best());
        let _ = e.write_all(c);
        e.finish().map(|v| v.len()).unwrap_or(0)
    };
    let variants: Vec<Value> = m
        .variants
        .iter()
        .map(|v| {
            let entry: Value = b.chunks.get(&v.entry).and_then(|c| serde_json::from_slice(c).ok()).unwrap_or_default();
            let hashes: Vec<&str> = entry["chunks"].as_array().into_iter().flatten().filter_map(|h| h.as_str()).collect();
            let kinds: Vec<String> = hashes.iter().filter_map(|h| m.chunk(h)).map(|c| c.kind.clone()).collect();
            let raw: usize = hashes.iter().filter_map(|h| b.chunks.get(*h)).map(|c| c.len()).sum();
            let zipped: usize = hashes.iter().filter_map(|h| b.chunks.get(*h)).map(|c| gz(c)).sum();
            json!({ "tier": format!("{:?}", v.tier), "requires": v.requires, "chunks": kinds, "bytes": raw, "gzip": zipped })
        })
        .collect();
    let caps = |modules: &[&str], script: bool| {
        let mut c = datars_engine::bundle::capabilities(script, Vec::new());
        c.modules = modules.iter().map(|m| m.to_string()).collect();
        if !script {
            c.packages.clear();
        }
        c
    };
    let profiles = [
        ("web (core engine)", caps(&["core", "graph"], false)),
        ("web (full engine)", caps(&["core", "graph", "sandbox"], true)),
        ("app (DatarsKit / Android, script allowed)", caps(&["core", "graph", "sandbox"], true)),
        ("app without script", caps(&["core", "graph"], false)),
        ("playback-only runtime", caps(&["core"], false)),
    ];
    let picks: Vec<Value> = profiles
        .iter()
        .map(|(name, c)| match m.select(c) {
            Ok(v) => json!({ "runtime": name, "plays": format!("{:?}", v.tier) }),
            Err(e) => json!({ "runtime": name, "error": e.to_string() }),
        })
        .collect();
    Ok(json!({ "id": m.id, "revision": m.revision, "title": m.title, "signed": m.signature.is_some(), "variants": variants, "picks": picks, "fonts": m.fonts }))
}

pub fn bundle_text(v: &Value) -> String {
    let mut s = format!("{} (revision {}){}\n", v["id"].as_str().unwrap_or(""), v["revision"].as_str().unwrap_or(""), if v["signed"] == true { ", signed" } else { "" });
    for var in v["variants"].as_array().into_iter().flatten() {
        s += &format!("  {}  {:>8} bytes  {:>7} gzipped  [{}]\n", var["tier"].as_str().unwrap_or(""), var["bytes"], var["gzip"], var["chunks"].as_array().into_iter().flatten().filter_map(|c| c.as_str()).collect::<Vec<_>>().join(", "));
    }
    let fonts = v["fonts"].as_array().cloned().unwrap_or_default();
    if !fonts.is_empty() {
        s += "fonts:\n";
        for f in &fonts {
            s += &format!("  {} {}{}  {}  from {}\n", f["family"].as_str().unwrap_or(""), f["weight"], if f["italic"] == true { " italic" } else { "" }, f["licence"].as_str().unwrap_or(""), f["from"].as_str().unwrap_or(""));
        }
    }
    s += "picks:\n";
    for p in v["picks"].as_array().into_iter().flatten() {
        s += &format!("  {:<44} {}\n", p["runtime"].as_str().unwrap_or(""), p["plays"].as_str().or(p["error"].as_str()).unwrap_or(""));
    }
    s
}

/// `datars fonts`: every font token — what it names, where its face comes from, the face the
/// engine draws with, whether that is the token's own family, and its licence.
pub fn fonts_report(engine: &datars_engine::Engine) -> Vec<serde_json::Value> {
    let db = engine.fonts();
    let infos = db.faces();
    engine
        .theme()
        .fonts
        .iter()
        .map(|(token, spec)| {
            let face = db.face_id(&spec.stack().join(", "), spec.weight, spec.italic);
            let info = face.as_ref().and_then(|id| infos.iter().find(|f| &f.id == id));
            let loaded = spec.primary().is_some_and(|fam| info.is_some_and(|i| i.family.eq_ignore_ascii_case(&fam)));
            let licence = face.as_ref().and_then(|id| db.face_data(id)).map(|(b, i)| datars_build::fonts::licence(b, i).id);
            serde_json::json!({
                "token": token, "family": spec.stack(), "weight": spec.weight, "italic": spec.italic,
                "source": spec.source_url(), "face": face, "loaded": loaded,
                "licence": licence, "fs_type": info.map(|i| i.fs_type),
            })
        })
        .collect()
}

/// Loads a document with its files from a directory (the CLI's `load`).
pub type LoadFn = dyn Fn(&str, Option<&std::path::Path>) -> Result<datars_engine::Engine, String>;

/// `datars profile`, for explorable views: what a reader's pans and zooms cost per frame, from the
/// first frame of a freshly loaded document (indexing point pyramids included) to zooms and pans at
/// several depths — engine frame time (fill, display list, hash; no rasterizing: that's the
/// host's GPU) and what it drew. Nothing is printed for documents without an explorable view.
pub fn profile_explore(source: &str, dir: &std::path::Path, engine: &mut datars_engine::Engine, load: &LoadFn) -> Result<(), String> {
    use datars_engine::Pointer;
    let vp = engine.viewport();
    let (cx, cy) = (vp.width / 2.0, vp.height / 2.0);
    engine.goto(0);
    engine.frame(1000.0);
    if !engine.wheel(datars_math::Vec2::new(cx, cy), 0.0) {
        return Ok(());
    }
    // A fresh engine: the first frame pays for indexing.
    let mut fresh = load(source, Some(dir))?;
    let t = std::time::Instant::now();
    fresh.frame(0.0);
    let first = t.elapsed().as_secs_f64() * 1000.0;
    let ps = fresh.point_stats();
    if ps.rows > 0 {
        println!("explore: first frame {first:.0} ms ({} rows indexed into point pyramids)", fmt_int(ps.rows));
    } else {
        println!("explore: first frame {first:.1} ms");
    }
    let mut now = 1000.0;
    let frame = |e: &mut datars_engine::Engine, now: &mut f64| -> f64 {
        *now += 1.0;
        let t = std::time::Instant::now();
        let f = e.frame(*now);
        std::hint::black_box(f.hash());
        t.elapsed().as_secs_f64() * 1000.0
    };
    let median = |mut v: Vec<f64>| {
        v.sort_by(|a, b| a.total_cmp(b));
        v[v.len() / 2]
    };
    let report = |e: &datars_engine::Engine, what: &str, ms: f64| {
        let s = e.point_stats();
        let drawn = if s.rows > 0 { format!("   {} of {} points drawn (level {}, {} tiles)", fmt_int(s.drawn), fmt_int(s.rows), s.level, s.tiles) } else { String::new() };
        println!("  {what:<24} frame {ms:>7.2} ms{drawn}");
    };
    // Zoom in about the centre, ×2 at a time; at each depth, a pan (drag) measured over a few frames.
    frame(engine, &mut now);
    let whole: Vec<f64> = (0..5).map(|_| frame(engine, &mut now)).collect();
    report(engine, "whole", median(whole));
    for step in 1..=10 {
        engine.set_clock(now);
        engine.pointer(Pointer::Wheel { x: cx, y: cy, delta: -462.0 });
        let zoom_ms = frame(engine, &mut now);
        let mut pans = Vec::new();
        for k in 0..6 {
            let dx = if k % 2 == 0 { 40.0 } else { -40.0 };
            engine.pointer(Pointer::Down { x: cx, y: cy });
            engine.pointer(Pointer::Move { x: cx + dx, y: cy });
            engine.pointer(Pointer::Up { x: cx + dx, y: cy });
            pans.push(frame(engine, &mut now));
        }
        report(engine, &format!("zoom ×{} (step)", 1u64 << step), zoom_ms);
        report(engine, &format!("zoom ×{} (pan)", 1u64 << step), median(pans));
    }
    Ok(())
}

fn fmt_int(n: u64) -> String {
    let s = n.to_string();
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if i > 0 && (s.len() - i).is_multiple_of(3) {
            out.push(',');
        }
        out.push(c);
    }
    out
}

