/** The resolved colours, as a reader with `kind` would see them (for the chart: simulated inks). */
function simulated(r, kind) {
  const out = {};
  for (const [k, v] of Object.entries(r)) {
    if (isHex(v)) out[k] = simulate(v, kind);
    else if (Array.isArray(v) && v.length && v.every(isHex)) {
      const colors = v.map((c) => simulate(c, kind));
      out[k] = k === "categorical" ? colors : { kind: k === "diverging" ? "diverging" : "sequential", colors };
    }
  }
  return out;
}
