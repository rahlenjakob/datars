/** A face this site serves, as a host hands it to a chart: the runtime fetches `src`. */
const face = (family, weight, file) => ({ family: [family], weight, src: new URL(`fonts/${file}.ttf`, SITE).href });
const isFont = (v) => !!v && typeof v === "object" && !Array.isArray(v) && "family" in v;
const bytes = new Map(), loaded = new Map();
/** A face's bytes, fetched once for every chart on the page. */
function loadFace(url) {
  if (!bytes.has(url)) {
    const p = fetch(url).then((r) => (r.ok ? r.arrayBuffer() : Promise.reject(new Error(`${r.status} ${url}`)))).then((b) => new Uint8Array(b));
    p.then((b) => loaded.set(url, b), () => bytes.delete(url));
    bytes.set(url, p);
  }
  return bytes.get(url);
}
const facesOf = (tokens) => Object.values(tokens).filter(isFont).map((v) => v.src);
/** How a face reads in code: the path a host would serve it from. */
const faceFile = (v) => new URL(v.src).pathname.replace(/^.*\/fonts\//, "").replace(/\.ttf$/, "");
const faceCode = (v) => `face(${JSON.stringify(v.family[0])}, ${v.weight}, ${JSON.stringify(faceFile(v))})`;
/** The helper the runtime code uses for faces (shown when a layer names one). */
const FACE_HELPER = "// A face on your server: the chart fetches it.\nconst face = (family, weight, file) => ({ family: [family], weight, src: `/fonts/${file}.ttf` });\n";
const faceTs = (v) => `font.file(${JSON.stringify(v.family[0])}, "fonts/${faceFile(v)}.ttf", { weight: ${v.weight} })`;

/** Every chart this page styles: answers its face requests from the page's cache, and hands
 * over faces a new token layer names in the same task as the tokens (never drawn in a fallback). */
const held = new WeakMap();
function wire(view) {
  held.set(view, new Set());
  view.addEventListener("datarequest", (ev) => {
    if (!ev.detail.name.startsWith("font:")) return;
    const got = bytes.get(new URL(ev.detail.url, location.href).href);
    if (!got) return;
    ev.preventDefault();
    ev.detail.respond(got);
    held.get(view).add(ev.detail.url);
  });
}
function put(view, tokens) {
  view.setTokens(tokens);
  if (!view.dataset.renderer) return;
  const has = held.get(view);
  for (const v of Object.values(tokens)) {
    if (!isFont(v) || has.has(v.src) || !loaded.has(v.src)) continue;
    try { view.provideData(`font:${v.family[0]}-${v.weight}`, loaded.get(v.src)); } catch { /* not asked for */ }
    has.add(v.src);
  }
}

/** The theme the engine resolved for a chart now (`status.tokens.tokens`): every token's value. */
const resolvedOf = (view) => view.status?.tokens?.tokens ?? null;

/** In-between frames for a change of look: each colour token and palette eased from what the chart
 * showed to what it will, in OKLab, handed over once a frame (the engine itself snaps colours). */
const BLEND_MS = 480;
const blends = new Map();
function blend(view, from, to, host, onFrame) {
  blends.set(view, { from, to, host, onFrame, t0: 0 });
  if (blends.size === 1) requestAnimationFrame(step);
}
function frameInks(from, to, e) {
  const inks = {};
  for (const [k, b] of Object.entries(to)) {
    const a = from[k];
    if (isHex(a) && isHex(b) && a !== b) inks[k] = mix(a, b, e);
    else if (Array.isArray(a) && Array.isArray(b) && b.length && b.every(isHex)) {
      const colors = b.map((c, i) => (isHex(a[i % a.length]) ? mix(a[i % a.length], c, e) : c));
      inks[k] = k === "categorical" ? colors : { kind: k === "diverging" ? "diverging" : "sequential", colors };
    }
  }
  return inks;
}
function step(now) {
  for (const [view, b] of blends) {
    if (!b.t0) b.t0 = now;
    const t = Math.min(1, (now - b.t0) / BLEND_MS);
    const e = t < 0.5 ? 4 * t * t * t : 1 - (-2 * t + 2) ** 3 / 2; // cubic-in-out, the engine's default
    if (t >= 1) {
      put(view, b.host);
      b.onFrame?.(b.to);
      blends.delete(view);
      continue;
    }
    const inks = frameInks(b.from, b.to, e);
    put(view, { ...b.host, ...inks });
    b.onFrame?.({ ...b.to, ...inks });
  }
  if (blends.size) requestAnimationFrame(step);
}
/** Hand `view` a new mode and token layer, easing its colours there from what it shows. */
async function restyle(view, { viewMode, tokens }, { animate = true, onFrame } = {}) {
  await Promise.all(facesOf(tokens).map((u) => loadFace(u).catch(() => {})));
  const from = animate && !reduced && view.dataset.renderer ? resolvedOf(view) : null;
  blends.delete(view);
  const t0 = performance.now();
  if (view.getAttribute("mode") !== viewMode) view.setAttribute("mode", viewMode);
  put(view, tokens);
  const ms = performance.now() - t0;
  const to = resolvedOf(view);
  if (from && to) {
    // The first in-between frame, in the same task: the target's colours are never drawn first.
    put(view, { ...tokens, ...frameInks(from, to, 0) });
    blend(view, from, to, tokens, onFrame);
  } else if (to) onFrame?.(to);
  return { ms, to };
}

