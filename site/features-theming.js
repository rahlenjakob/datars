/** One colour → a theme, as the theme studio's "from your brand colour" (white paper) builds it:
 * the brand as accent, palettes the engine generates from it, a lighter accent on dark paper and a
 * darker one in high contrast where it wouldn't read — so the studio opens on exactly this. */
function brandTheme(hex) {
  const nightPaper = "#111318";
  const lift = lightnessNeeded(hex, nightPaper, 3, 1);
  const sink = lightnessNeeded(hex, "#ffffff", 4.5, -1);
  const [, C, H] = lch(hex);
  const nightRamp = { kind: "sequential", colors: [0.3, 0.42, 0.56, 0.72, 0.88].map((L, i) => fromLch(L, Math.min(C, 0.16) * (0.55 + 0.1 * i), H)) };
  const t = {
    name: "my-brand", scheme: "light", from: "brand", locked: [],
    tokens: {
      brand: hex,
      accent: "$brand",
      categorical: { generate: "categorical", from: "$accent", n: 8 },
      sequential: { generate: "sequential", from: "$brand", n: 5 },
      diverging: { generate: "diverging", from: opposite(hex), to: "$brand", n: 7 },
    },
    modes: { dark: { sequential: nightRamp }, "high-contrast": {} },
  };
  if (lift) t.modes.dark.accent = `lighten($brand, ${lift})`;
  if (sink) t.modes["high-contrast"].accent = `darken($brand, ${sink})`;
  return t;
}
