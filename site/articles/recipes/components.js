// formation: the dots form a word (5×7 font) or a silhouette mask; the same keys fly between
// formations. The lit cells are a small table in the expression (an array literal); dot n takes
// cell n mod C, jittered inside it by a hash of n.
export const formation = recipe({
  id: "@articles/components/formation",
  doc: "Dots forming a word (5×7 font) or a silhouette (`shape`): each dot in one lit cell, jittered.",
  params: { data: t.table(), key: t.field(), value: t.field("The group (colours the dots)."), word: t.string("DATA"), shape: t.string(), colors: t.string(), dot: t.number(1.5) },
  expand(p, cx) {
    const cells = [];
    let cols, rows;
    const mask = p.shape ? SHAPES[p.shape] : undefined;
    if (mask) {
      mask.forEach((row, y) => [...row].forEach((ch, x) => { if (ch === "#") cells.push([x, y]); }));
      cols = mask[0].length; rows = mask.length;
    } else {
      const letters = [...String(p.word).toUpperCase()].filter((c) => FONT[c]);
      letters.forEach((c, li) => FONT[c].forEach((row, y) => [...row].forEach((ch, x) => { if (ch === "#") cells.push([li * 6 + x, y]); })));
      cols = Math.max(1, letters.length * 6 - 1); rows = 7;
    }
    if (cells.length === 0) cells.push([0, 0]);
    const C = cells.length;
    const X = JSON.stringify(cells.map((c) => c[0])), Y = JSON.stringify(cells.map((c) => c[1]));
    const rowsT = cx.table("rows", p.data, op.derive("one", 1), op.window("cumsum", "one", "n"));
    const i = `((d.n - 1) % ${C})`;
    const h = (k) => `(sin(d.n * 12.9898 + ${k} * 78.233) * 43758.5453 - floor(sin(d.n * 12.9898 + ${k} * 78.233) * 43758.5453))`;
    const u = `min(box.w / ${cols + 2}, box.h / ${rows + 2})`;
    const own = String(p.colors || "").split(/\s+/).filter(Boolean);
    const fill = own.length
      ? e(`${JSON.stringify(own)}[(d.n - 1) % ${own.length}]`)
      : e(`"$categorical[" + ((d.${p.value} + ${mask ? 0 : `${X}[${i}] % 3`}) % 10) + "]"`);
    return instances({
      key: "cloud", from: rowsT, instanceKey: e(`d.${p.key}`),
      x: e(`(box.w - ${cols} * ${u}) / 2 + (${X}[${i}] + ${h(5)}) * ${u}`),
      y: e(`(box.h - ${rows} * ${u}) / 2 + (${Y}[${i}] + ${h(6)}) * ${u}`),
      r: p.dot, fill, opacity: 0.9,
    });
  },
});

