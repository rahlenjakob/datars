// @articles/components — chart types beyond the standard library, as a datars user package
// (docs/07 §Custom components). Plain ES module against the public SDK only; no engine changes.
// Recipes never see rows (they're O(1) in data): per-row layout is table ops and expressions the
// engine evaluates. All six are here: bubbles, petals, seasons, spiral, cloud and formation.

import { e, group, instances, op, recipe, repeat, shape, geom, t, text } from "@datars/sdk";

const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const YEARS = ["#313695", "#4575b4", "#abd9e9", "#fdae61", "#d73027", "#a50026"];
const TAU = 6.283185307179586;
const q = (s) => JSON.stringify(s);

// bubbles: packed circles, area ∝ value, keyed by the row (bars and slices morph into them).
export const bubbles = recipe({
  id: "@articles/components/bubbles",
  doc: "Packed circles: area ∝ value, labelled inside when they fit.",
  params: { data: t.table(), key: t.field(), value: t.field(), gap: t.number(3), unit: t.string("") },
  expand(p, cx) {
    const packed = cx.table("pack", p.data, op.pack({ value: p.value, width: e("box.w"), height: e("box.h"), padding: p.gap }));
    return group({
      key: "bubbles",
      children: [
        repeat(packed, shape(geom.circle({ cx: e("d.cx"), cy: e("d.cy"), r: e("d.r") }), {
          fill: e(`key.color(d.${p.key}) ?? "$accent"`),
          semantics: { role: "datum", label: e(`\`\${key.name(d.${p.key})}: \${format(d.${p.value}, ",.1~f")}${p.unit}\``), value: e(`d.${p.value}`) },
          pickable: true,
        })),
        group({ key: "labels", children: [repeat(packed, text(e(`\`\${d.${p.key}} \${format(d.${p.value}, ",.1~f")}${p.unit}\``), [e("d.cx"), e("d.cy + 4")], {
          when: e("d.r > 16"),
          style: { size: e("d.r > 40 ? 13 : 11"), weight: 700, ink: "$paper", align: "middle" },
        }))] }),
      ],
    });
  },
});

// petals: one petal per row in equal slots around a core, length ∝ √value.
export const petals = recipe({
  id: "@articles/components/petals",
  doc: "Petals around a centre: equal slots, petal length ∝ √value.",
  params: { data: t.table(), key: t.field(), value: t.field(), width: t.number(0.55, "Petal width as a share of its slot.") },
  expand(p, cx) {
    const slots = cx.table("slots", p.data, op.derive("one", 1), op.pie({ value: "one", sort: "none", as: ["a0", "a1"] }));
    const R = "(min(box.w, box.h) / 2 - 26)";
    const L = `scale.len(d.${p.value})`;
    return group({
      key: "petals",
      scales: { len: { type: "sqrt", domain: { data: p.data, field: p.value }, range: [`=${R} * 0.2`, `=${R} * 0.88`], zero: true } },
      children: [
        // Each petal an ellipse along its slot's bisector, rotated about the centre.
        repeat(slots, shape(geom.ellipse({ cx: 0, cy: e(`-(${R} * 0.12 + ${L} / 2)`), rx: e(`max(2, sin((d.a1 - d.a0) * ${p.width} / 2) * (${R} * 0.12 + ${L} / 2))`), ry: e(`${L} / 2`) }), {
          transform: { rotate: e(`(d.a0 + d.a1) / 2 * 57.29577951308232`), translate: [e("box.w / 2"), e("box.h / 2 + 6")] },
          fill: e(`key.color(d.${p.key}) ?? "$accent"`),
          semantics: { role: "datum", label: e(`\`\${key.name(d.${p.key})}: \${format(d.${p.value}, ",.1~f")}\``), value: e(`d.${p.value}`) },
          pickable: true,
        })),
        shape(geom.circle({ cx: e("box.w / 2"), cy: e("box.h / 2 + 6"), r: e(`${R} * 0.12`) }), { key: "core", fill: "$paper", stroke: { paint: "$rule", width: 1 } }),
      ],
    });
  },
});

// seasons / spiral read (series = month, x = year, y = anomaly) points.
function yearFrac(data, x) {
  return `((d.${x} - table.min(${q(data)}, ${q(x)})) / max(1, table.max(${q(data)}, ${q(x)}) - table.min(${q(data)}, ${q(x)})))`;
}

// seasons: every month of every year as a dot — months across, anomaly up, coloured by year.
export const seasons = recipe({
  id: "@articles/components/seasons",
  doc: "Every month of every year as a dot: month across, value up, coloured by year.",
  params: { data: t.table(), series: t.field(), x: t.field(), y: t.field(), dot: t.number(2.6), label: t.prop("Dot label (tooltip).") },
  expand(p) {
    const f = yearFrac(p.data, p.x);
    return group({
      key: "seasons",
      scales: {
        m: { type: "band", domain: MONTHS, range: [34, "=box.w"], padding: 0 },
        v: { type: "linear", domain: { data: p.data, field: p.y }, range: ["=box.h - 24", 8], nice: true },
        c: { type: "sequential", domain: { data: p.data, field: p.x }, range: YEARS },
      },
      children: [
        repeat({ ticks: "v" }, group({ children: [
          shape(geom.segment({ x1: 34, y1: e("d.pos"), x2: e("box.w"), y2: e("d.pos") }), { stroke: { paint: e('d.value == 0 ? "$muted" : "$grid"'), width: 1 } }),
          text(e("`${d.value > 0 ? \"+\" : \"\"}${d.label}°`"), [28, e("d.pos + 4")], { style: { size: 10.5, ink: "$muted", align: "end" } }),
        ] })),
        repeat({ ticks: "m" }, text(e("d.label"), [e("d.pos + scale.m.bandwidth() / 2"), e("box.h - 6")], { style: { size: "$size.label", ink: "$muted", align: "middle" } })),
        instances({
          key: "dots", from: p.data, instanceKey: e(`d.${p.series} + "@" + d.${p.x}`),
          x: e(`scale.m(d.${p.series}) + scale.m.bandwidth() * (0.5 + (${f} - 0.5) * 0.7)`), y: e(`scale.v(d.${p.y})`),
          r: p.dot, fill: e(`scale.c(d.${p.x})`), label: p.label ?? e(`\`\${d.${p.series}} \${d.${p.x}}: \${format(d.${p.y}, "+.2f")} °C\``),
        }),
      ],
    });
  },
});

// spiral: the same dots wound around a circle, one turn per year, radius = anomaly.
export const spiral = recipe({
  id: "@articles/components/spiral",
  doc: "Months wound into a spiral: angle = month (+ year within it), radius = value, coloured by year.",
  params: { data: t.table(), series: t.field(), x: t.field(), y: t.field(), dot: t.number(2.6), rings: t.string("0,1,1.5"), label: t.prop("Dot label (tooltip).") },
  expand(p) {
    const f = yearFrac(p.data, p.x);
    const R = "(min(box.w, box.h) / 2 - 22)";
    const a = `((scale.mi(d.${p.series}) + 0.15 + 0.7 * ${f}) / 12 * ${TAU})`;
    const rings = String(p.rings).split(",").map(Number).filter((v) => !Number.isNaN(v));
    return group({
      key: "spiral",
      scales: {
        mi: { type: "point", domain: MONTHS, range: [0, 11], padding: 0 },
        rr: { type: "linear", domain: { data: p.data, field: p.y }, range: [`=${R} * 0.12`, `=${R}`], nice: true },
        c: { type: "sequential", domain: { data: p.data, field: p.x }, range: YEARS },
      },
      children: [
        group({ key: "rings", children: rings.map((v) => group({ key: `ring-${v}`, children: [
          shape(geom.circle({ cx: e("box.w / 2"), cy: e("box.h / 2"), r: e(`max(0, scale.rr(${v}))`) }), { stroke: { paint: v === 1.5 ? "#d73027" : "$grid", width: v === 1.5 ? 1.2 : 1 } }),
          text(`${v > 0 ? "+" : ""}${v}°C`, [e("box.w / 2 + 4"), e(`box.h / 2 - scale.rr(${v}) - 3`)], { style: { size: 10.5, ink: v === 1.5 ? "#d73027" : "$muted" }, halo: ["$paper", 2] }),
        ] })) }),
        group({ key: "months", children: MONTHS.map((m, i) => text(m, [e(`box.w / 2 + (${R} + 12) * sin(${(i + 0.5) / 12 * TAU})`), e(`box.h / 2 + 4 - (${R} + 12) * cos(${(i + 0.5) / 12 * TAU})`)], { key: m, style: { size: "$size.label", ink: "$muted", align: "middle" } })) }),
        instances({
          key: "dots", from: p.data, instanceKey: e(`d.${p.series} + "@" + d.${p.x}`),
          x: e(`box.w / 2 + scale.rr(d.${p.y}) * sin(${a})`), y: e(`box.h / 2 - scale.rr(d.${p.y}) * cos(${a})`),
          r: p.dot, fill: e(`scale.c(d.${p.x})`), label: p.label ?? e(`\`\${d.${p.series}} \${d.${p.x}}: \${format(d.${p.y}, "+.2f")} °C\``),
        }),
        text(e(`\`\${table.min(${q(p.data)}, ${q(p.x)})}–\${table.max(${q(p.data)}, ${q(p.x)})}\``), [e("box.w / 2"), e("box.h / 2 + 4")], { key: "years", style: { size: 13, weight: 700, ink: "$ink", align: "middle" } }),
      ],
    });
  },
});

// cloud: two seeded gaussian clusters of dots (by group), keyed by the row — later formations
// fly the same keys elsewhere.
export const cloud = recipe({
  id: "@articles/components/cloud",
  doc: "Seeded gaussian clusters of dots, one cluster per group (0/1).",
  params: { data: t.table(), key: t.field(), value: t.field("The group (0 or 1)."), dot: t.number(1.5) },
  expand(p, cx) {
    // A row number, then a deterministic hash of it (sin-fract) for Box–Muller normals.
    const rows = cx.table("rows", p.data, op.derive("one", 1), op.window("cumsum", "one", "n"));
    const h = (k) => `(sin(d.n * 12.9898 + ${k} * 78.233) * 43758.5453 - floor(sin(d.n * 12.9898 + ${k} * 78.233) * 43758.5453))`;
    const gauss = (k1, k2) => `(sqrt(-2 * log(max(1e-9, ${h(k1)}))) * cos(${TAU} * ${h(k2)}))`;
    return instances({
      key: "cloud", from: rows, instanceKey: e(`d.${p.key}`),
      x: e(`box.w * ((d.${p.value} % 2 == 0 ? 0.36 : 0.64) + ${gauss(1, 2)} * 0.11)`),
      y: e(`box.h * ((d.${p.value} % 2 == 0 ? 0.56 : 0.42) + ${gauss(3, 4)} * 0.13)`),
      r: p.dot, fill: e(`d.${p.value} % 2 == 0 ? "$categorical[0]" : "$categorical[1]"`), opacity: 0.85,
    });
  },
});

